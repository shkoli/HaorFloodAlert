# Canonical 10-column schema, taken from daily_validation.py CSV_COLUMNS --
# this is the schema the logging script actually writes today.
CSV_COLUMNS = [
    "date", "time", "flood_probability", "risk_level",
    "sw269_water_level", "forecast_rain_72h", "soil_moisture", "barak_discharge",
    "danger_level", "wl_status",
]
SW269_DANGER = 6.05  # daily_validation.py:33 -- SW269_DANGER, metres

# daily_validation.py's own risk_label() thresholds (NOT config.RISK_THRESHOLDS,
# which uses different cut points: EXTREME .85/HIGH .65/MEDIUM .40). The
# risk_level column in the log was generated by daily_validation.py, so its
# thresholds are the relevant ones for interpreting that column. Flagged as
# a real inconsistency between the two threshold definitions in the codebase.
DAILY_VALIDATION_RISK_THRESHOLDS = [(0.70, "CRITICAL"), (0.50, "HIGH"), (0.30, "MODERATE"), (0.00, "LOW")]
RISK_RANK = {"LOW": 0, "MODERATE": 1, "HIGH": 2, "CRITICAL": 3}

NEAR_DANGER_BAND_CM = 50  # documented choice: "near-danger" = within 50cm of SW269_DANGER


def parse_validation_log(csv_path: Path) -> dict:
    """
    Robust parser for data/daily_validation_log.csv, which has two real,
    documented data-quality defects found while building this script:

      1. STALE HEADER: row 1 declares only the first 8 of CSV_COLUMNS
         (daily_validation.py's schema grew from 8 to 10 columns --
         danger_level, wl_status -- after the header was first written, and
         the header was never rewritten). Every data row this script has
         seen has either 8 fields (matches the stale header; only the very
         first data row) or 10 fields (matches the current CSV_COLUMNS).
         RULE: parse by field COUNT per row against CSV_COLUMNS, not by the
         file's declared header. Rows with 8 fields get danger_level filled
         from SW269_DANGER and wl_status computed the same way
         daily_validation.py itself computes it (cm above/below danger).
      2. DUPLICATE ROWS: some calendar days have 2-3 readings (the script
         was run more than once that day), and one pair of rows
         (2026-05-30 19:04, both entries) is a byte-for-byte exact
         duplicate. RULE: exact-duplicate rows are dropped first (kept
         once). Remaining same-day multi-reading rows are then reduced to
         one row per day by taking the reading with the MAX
         flood_probability that day (the model's own peak-risk reading for
         that day; ties broken by latest `time`).
    """
    raw_lines = csv_path.read_text(encoding="utf-8").splitlines()
    header_line = raw_lines[0]
    data_lines = [ln for ln in raw_lines[1:] if ln.strip()]

    parsed_rows = []
    malformed = []
    for ln in data_lines:
        fields = ln.split(",")
        if len(fields) not in (8, 10):
            malformed.append(ln)
            continue
        padded = fields + [None] * (10 - len(fields))
        parsed_rows.append(dict(zip(CSV_COLUMNS, padded)))

    n_raw_rows = len(data_lines)

    df = pd.DataFrame(parsed_rows)
    for col in ("flood_probability", "sw269_water_level", "forecast_rain_72h",
                "soil_moisture", "barak_discharge"):
        df[col] = pd.to_numeric(df[col], errors="coerce")
    df["danger_level"] = pd.to_numeric(df["danger_level"], errors="coerce")
    n_filled_danger = int(df["danger_level"].isna().sum())
    df["danger_level"] = df["danger_level"].fillna(SW269_DANGER)

    def _status(row):
        if row["wl_status"] not in (None, "") and not pd.isna(row["wl_status"]):
            return row["wl_status"]
        diff_cm = round((row["sw269_water_level"] - row["danger_level"]) * 100)
        if diff_cm > 0:
            return f"{abs(diff_cm)} cm above danger level"
        elif diff_cm < 0:
            return f"{abs(diff_cm)} cm below danger level"
        return "at danger level"

    df["wl_status"] = df.apply(_status, axis=1)

    # 1. Drop exact-duplicate rows (identical across all 10 fields).
    n_before = len(df)
    df = df.drop_duplicates(subset=CSV_COLUMNS, keep="first").reset_index(drop=True)
    n_exact_duplicates_dropped = n_before - len(df)

    # 2. Reduce multi-reading days to one row: max flood_probability, ties
    #    broken by latest `time` string (HH:MM sorts lexicographically same
    #    as chronologically within a day).
    df = df.sort_values(["date", "flood_probability", "time"],
                         ascending=[True, False, False])
    n_readings_per_day = df.groupby("date").size().to_dict()
    daily = df.drop_duplicates(subset=["date"], keep="first").sort_values("date").reset_index(drop=True)
    daily["n_readings_that_day"] = daily["date"].map(n_readings_per_day)

    return {
        "header_line_declared": header_line,
        "n_raw_data_rows": n_raw_rows,
        "n_malformed_rows_skipped": len(malformed),
        "malformed_rows": malformed,
        "n_danger_level_filled_from_default": n_filled_danger,
        "n_exact_duplicate_rows_dropped": n_exact_duplicates_dropped,
        "daily": daily,
    }


def categorize_wl(distance_cm: float) -> str:
    if distance_cm < -NEAR_DANGER_BAND_CM:
        return "SAFE"
    elif distance_cm < 0:
        return "NEAR"
    else:
        return "AT_OR_ABOVE"


def build_prospective_validation() -> dict:
    csv_path = DATA_DIR / "daily_validation_log.csv"
    parsed = parse_validation_log(csv_path)
    daily = parsed["daily"].copy()

    daily["date_dt"] = pd.to_datetime(daily["date"])
    daily["distance_to_danger_cm"] = ((daily["sw269_water_level"] - daily["danger_level"]) * 100).round().astype(int)
    daily["wl_category"] = daily["distance_to_danger_cm"].apply(categorize_wl)
    daily["risk_rank"] = daily["risk_level"].map(RISK_RANK)

    day_rows = daily.to_dict("records")

    # ── Monitoring coverage ────────────────────────────────────────────────
    first_date = daily["date_dt"].min()
    last_date = daily["date_dt"].max()
    full_range = pd.date_range(first_date, last_date, freq="D")
    monitored_dates = set(daily["date_dt"])
    missing_dates = [d for d in full_range if d not in monitored_dates]

    # Contiguous missing-date gaps, for a readable report.
    gaps = []
    if missing_dates:
        gap_start = missing_dates[0]
        prev = missing_dates[0]
        for d in missing_dates[1:]:
            if (d - prev).days > 1:
                gaps.append((gap_start, prev))
                gap_start = d
            prev = d
        gaps.append((gap_start, prev))

    # ── Alert episodes: consecutive-CALENDAR-DAY runs of monitored days with
    #    risk_level in {HIGH, CRITICAL}. A monitoring gap or a drop below
    #    HIGH ends the episode. This deliberately does NOT bridge gaps --
    #    a day with no log entry is not assumed to have continued the alert.
    episodes = []
    current = None
    for i, row in enumerate(day_rows):
        is_alert = row["risk_level"] in ("HIGH", "CRITICAL")
        if is_alert:
            if current is not None and (row["date_dt"] - current["end_dt"]).days == 1:
                current["end_dt"] = row["date_dt"]
                current["days"].append(row)
            else:
                if current is not None:
                    episodes.append(current)
                current = {"start_dt": row["date_dt"], "end_dt": row["date_dt"], "days": [row]}
        else:
            if current is not None:
                episodes.append(current)
                current = None
    if current is not None:
        episodes.append(current)

    episode_summaries = []
    for ep in episodes:
        peak_row = max(ep["days"], key=lambda r: r["flood_probability"])
        episode_summaries.append({
            "start_date": ep["start_dt"].strftime("%Y-%m-%d"),
            "end_date": ep["end_dt"].strftime("%Y-%m-%d"),
            "n_calendar_days": (ep["end_dt"] - ep["start_dt"]).days + 1,
            "n_monitored_days_in_episode": len(ep["days"]),
            "peak_probability": float(peak_row["flood_probability"]),
            "peak_date": peak_row["date"],
        })

    def episode_containing(date_dt):
        for ep, summ in zip(episodes, episode_summaries):
            if ep["start_dt"] <= date_dt <= ep["end_dt"]:
                return summ
        return None

    # ── Near-danger approach events: SAFE -> (NEAR or AT_OR_ABOVE) between
    #    two CONSECUTIVE MONITORED days. If the gap between those two
    #    monitored days is >3 calendar days, the transition is flagged
    #    "unverified" (we have no data on what happened in between).
    approaches = []
    danger_crossings = []
    for i in range(1, len(day_rows)):
        prev_row, row = day_rows[i - 1], day_rows[i]
        gap_days = (row["date_dt"] - prev_row["date_dt"]).days
        if prev_row["wl_category"] == "SAFE" and row["wl_category"] in ("NEAR", "AT_OR_ABOVE"):
            ep = episode_containing(row["date_dt"])
            approaches.append({
                "approach_date": row["date"],
                "new_category": row["wl_category"],
                "water_level_m": float(row["sw269_water_level"]),
                "distance_to_danger_cm": int(row["distance_to_danger_cm"]),
                "gap_days_since_prior_monitored_reading": gap_days,
                "unverified_large_gap": gap_days > 3,
                "enclosing_alert_episode": ep,
                "lead_time_days": (
                    (row["date_dt"] - datetime.strptime(ep["start_date"], "%Y-%m-%d")).days
                    if ep else None
                ),
                "lead_time_note": (
                    "Model risk_level was HIGH/CRITICAL for lead_time_days before "
                    "water level entered the near-danger band."
                    if ep else
                    "No HIGH/CRITICAL alert episode covers this date -- the model "
                    "did not flag elevated risk when water approached near-danger."
                ),
            })
        if row["wl_category"] == "AT_OR_ABOVE" and prev_row["wl_category"] != "AT_OR_ABOVE":
            ep = episode_containing(row["date_dt"])
            danger_crossings.append({
                "crossing_date": row["date"],
                "water_level_m": float(row["sw269_water_level"]),
                "distance_to_danger_cm": int(row["distance_to_danger_cm"]),
                "gap_days_since_prior_monitored_reading": gap_days,
                "unverified_large_gap": gap_days > 3,
                "lead_time_days": (
                    (row["date_dt"] - datetime.strptime(ep["start_date"], "%Y-%m-%d")).days
                    if ep else None
                ),
            })

    # ── Mismatch days: risk_rank outside the expected band for wl_category.
    #    SAFE -> expected {LOW,MODERATE}; NEAR -> expected {MODERATE,HIGH};
    #    AT_OR_ABOVE -> expected {HIGH,CRITICAL}. This is a mechanical,
    #    stated-in-advance rule -- see interpretation caveats in the summary
    #    (an OVER_ALERT while SAFE is exactly what a leading 72h-ahead
    #    indicator with real lead time is supposed to look like; it is not
    #    automatically a model error).
    expected_band = {"SAFE": (0, 1), "NEAR": (1, 2), "AT_OR_ABOVE": (2, 3)}
    mismatches = []
    for row in day_rows:
        lo, hi = expected_band[row["wl_category"]]
        if not (lo <= row["risk_rank"] <= hi):
            mismatches.append({
                "date": row["date"],
                "risk_level": row["risk_level"],
                "wl_category": row["wl_category"],
                "distance_to_danger_cm": int(row["distance_to_danger_cm"]),
                "direction": "OVER_ALERT" if row["risk_rank"] > hi else "UNDER_ALERT",
            })

    daily_log_out = [
        {
            "date": r["date"],
            "flood_probability": float(r["flood_probability"]),
            "risk_level": r["risk_level"],
            "sw269_water_level_m": float(r["sw269_water_level"]),
            "danger_level_m": float(r["danger_level"]),
            "distance_to_danger_cm": int(r["distance_to_danger_cm"]),
            "wl_category": r["wl_category"],
            "forecast_rain_72h_mm": float(r["forecast_rain_72h"]),
            "soil_moisture_pct": float(r["soil_moisture"]),
            "barak_discharge_cumecs": float(r["barak_discharge"]),
            "n_readings_that_day": int(r["n_readings_that_day"]),
        }
        for r in day_rows
    ]

    return {
        "source_file": "data/daily_validation_log.csv",
        "data_quality_issues": {
            "stale_header": (
                f"Row 1 declares 8 columns ({parsed['header_line_declared']}) but "
                "daily_validation.py's CSV_COLUMNS (the schema the logger actually "
                "writes) has 10 -- danger_level and wl_status were added after the "
                "header was first written and it was never rewritten. Parsed by "
                "field count against the 10-column schema, not the file's own header."
            ),
            "n_raw_data_rows": parsed["n_raw_data_rows"],
            "n_rows_with_8_fields_danger_level_defaulted": parsed["n_danger_level_filled_from_default"],
            "n_malformed_rows_skipped": parsed["n_malformed_rows_skipped"],
            "malformed_rows": parsed["malformed_rows"],
            "n_exact_duplicate_rows_dropped": parsed["n_exact_duplicate_rows_dropped"],
            "risk_threshold_inconsistency": (
                "config.RISK_THRESHOLDS (EXTREME=.85/HIGH=.65/MEDIUM=.40) differs from "
                "daily_validation.py's own inline RISK_THRESHOLDS (CRITICAL=.70/HIGH=.50/"
                "MODERATE=.30). The risk_level column in this log was generated by "
                "daily_validation.py, so its thresholds (the latter) are used throughout "
                "this analysis."
            ),
        },
        "duplicate_day_handling_rule": (
            "Exact-duplicate rows dropped first (byte-for-byte identical across all "
            "10 fields). For calendar days with >1 remaining reading, the reading "
            "with the MAX flood_probability for that day is kept (ties broken by "
            "latest `time`); it is not a per-column max, so risk_level/water_level/"
            "etc. all come from that single representative reading."
        ),
        "near_danger_definition": (
            f"'Near-danger' (wl_category=NEAR) = within {NEAR_DANGER_BAND_CM} cm "
            f"below SW269_DANGER ({SW269_DANGER} m); 'AT_OR_ABOVE' = at or above "
            f"danger level; 'SAFE' = more than {NEAR_DANGER_BAND_CM} cm below."
        ),
        "coverage": {
            "first_date": first_date.strftime("%Y-%m-%d"),
            "last_date": last_date.strftime("%Y-%m-%d"),
            "total_calendar_days_in_range": len(full_range),
            "days_monitored": len(daily),
            "days_missed": len(missing_dates),
            "missed_date_gaps": [
                {"start": g[0].strftime("%Y-%m-%d"), "end": g[1].strftime("%Y-%m-%d"),
                 "n_days": (g[1] - g[0]).days + 1}
                for g in gaps
            ],
            "note": (
                "Nominal task scope was 'through 2026-07-03'; the live log actually "
                "contains one further reading on 2026-07-04, which is included here "
                "rather than discarded."
            ),
        },
        "alert_episodes": episode_summaries,
        "near_danger_approaches": approaches,
        "danger_level_crossings": danger_crossings,
        "mismatch_days": {
            "rule": (
                "A monitored day is a mismatch if risk_rank (LOW=0..CRITICAL=3) falls "
                "outside the expected band for that day's wl_category: "
                "SAFE->{LOW,MODERATE}, NEAR->{MODERATE,HIGH}, AT_OR_ABOVE->{HIGH,CRITICAL}."
            ),
            "interpretation_caveat": (
                "OVER_ALERT mismatches (CRITICAL/HIGH shown while water is still SAFE) "
                "are the expected signature of a 72h-ahead leading indicator providing "
                "real lead time -- see near_danger_approaches/lead_time_days, which are "
                "computed from exactly these days. They are not automatically errors. "
                "UNDER_ALERT mismatches (LOW/MODERATE shown while water is NEAR or "
                "AT_OR_ABOVE danger) are the more concerning category."
            ),
            "n_mismatch_days": len(mismatches),
            "n_over_alert": sum(1 for m in mismatches if m["direction"] == "OVER_ALERT"),
            "n_under_alert": sum(1 for m in mismatches if m["direction"] == "UNDER_ALERT"),
            "days": mismatches,
        },
        "daily_log": daily_log_out,
    }


