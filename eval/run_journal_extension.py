# PART 3 -- ALERT COST vs AVOIDED LOSS
# ═════════════════════════════════════════════════════════════════════════

SMS_COST_BDT = 0.25  # per the task specification for this analysis; not re-verified against a live BulkSMSBD price sheet in this run
FOCAL_CONTACTS_PER_UPAZILA_LOW = 15  # UNSOURCED scenario assumption -- see note below


def compute_alert_cost(damage_result: dict) -> dict:
    if damage_result.get("status") != "OK":
        return {"event": damage_result["event"], "status": "SKIPPED_NO_DAMAGE_DATA"}

    upazila_rows = damage_result["upazila_breakdown_no_warning"]
    total_avoided_by_salvage = {
        s["salvage_fraction"]: s["avoided_loss_bdt_crore"]
        for s in damage_result["warning_with_salvage_scenarios"]
    }

    per_upazila = []
    for row in upazila_rows:
        share = row["share_pct"] / 100.0
        contacts_low = FOCAL_CONTACTS_PER_UPAZILA_LOW
        contacts_high = row["families_affected"]
        cost_low_bdt = contacts_low * SMS_COST_BDT
        cost_high_bdt = contacts_high * SMS_COST_BDT

        avoided_by_salvage = []
        for s_frac, total_avoided_crore in total_avoided_by_salvage.items():
            upazila_avoided_crore = round(total_avoided_crore * share, 3)
            upazila_avoided_bdt = upazila_avoided_crore * 1e7
            avoided_by_salvage.append({
                "salvage_fraction": s_frac,
                "avoided_loss_bdt_crore": upazila_avoided_crore,
                "cost_effectiveness_ratio_low_contacts": (
                    round(upazila_avoided_bdt / cost_low_bdt, 1) if cost_low_bdt > 0 else None
                ),
                "cost_effectiveness_ratio_high_contacts": (
                    round(upazila_avoided_bdt / cost_high_bdt, 1) if cost_high_bdt > 0 else None
                ),
            })

        per_upazila.append({
            "upazila": row["upazila"],
            "families_exposed_no_warning": row["families_affected"],
            "contact_list_size_low_focal_points": contacts_low,
            "contact_list_size_high_every_exposed_family": contacts_high,
            "sms_cost_bdt_low": round(cost_low_bdt, 2),
            "sms_cost_bdt_high": round(cost_high_bdt, 2),
            "avoided_loss_vs_cost_by_salvage_scenario": avoided_by_salvage,
        })

    return {
        "event": damage_result["event"],
        "status": "OK",
        "sms_cost_bdt_per_message": SMS_COST_BDT,
        "sms_cost_source_note": (
            "BDT 0.25/message as specified for this analysis; not independently "
            "re-verified against a live BulkSMSBD (bulksmsbd.net) price sheet in "
            "this run."
        ),
        "contact_list_size_methodology": (
            "LOW bound: a fixed focal-point list per upazila "
            f"({FOCAL_CONTACTS_PER_UPAZILA_LOW} contacts -- UP chairman/DDMC focal "
            "point/community-leader roles, matching the sample contact roles in "
            "streamlit_app/pages/3_Alerts.py's sample CSV, i.e. a cascade-messaging "
            "model where leaders relay locally, not a real DDMC contact database. "
            "UNSOURCED scenario assumption.) "
            "HIGH bound: every farming family exposed in that upazila under the "
            "no-warning scenario (families_affected from utils.boro_damage."
            "upazila_breakdown -- a real, live-computed number from Part 2, not "
            "invented for this section)."
        ),
        "per_upazila": per_upazila,
    }


