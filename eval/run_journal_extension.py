FLOOD_DEPTH_CM_ASSUMPTION = 60.0  # UNSOURCED -- see note in damage scenario output
SALVAGE_FRACTIONS = [0.30, 0.50, 0.70]
# Stage-sensitivity uncertainty band: operationalizes the existing caption in
# streamlit_app/pages/6_CropDamage.py ("Actual field losses may vary by 20-40%
# depending on variety, water depth, and drainage conditions") -- NOT a new
# external citation. Applied as an asymmetric -25%/+40% perturbation to the
# STAGE_TABLE sensitivity used by estimate_damage().
SENS_LOW_FACTOR = 0.75
SENS_HIGH_FACTOR = 1.40


def run_damage_scenario(event: dict) -> dict:
    flood = compute_flood_extent(event["flood_end"])
    if flood.get("error"):
        return {"event": event["name"], "flood_end": event["flood_end"],
                "status": "UNAVAILABLE", "error": flood["error"]}

    haor = ee.Geometry.Rectangle(HAOR_BBOX)

    flood_start_str, flood_end_str = [s.strip() for s in flood["flood_period"].split("->")]
    end_dt = datetime.strptime(flood_end_str, "%Y-%m-%d")
    rain72_start = (end_dt - timedelta(days=3)).strftime("%Y-%m-%d")

    soil = fetch_soil_moisture(haor, flood_start_str, flood_end_str)
    rain72 = fetch_rainfall_chirps(haor, rain72_start, flood_end_str)
    upstream_vv = flood["upstream_vv"]

    month = end_dt.month
    prob = 1.0  # documented assumption: known historical event, not a forecast

    duration = estimate_duration(prob, soil, upstream_vv, rain72)

    sens_max_base = STAGE_TABLE.get(month, (0.30, "unknown", 7, 10))[0]
    sens_low = sens_max_base * SENS_LOW_FACTOR
    sens_high = min(1.0, sens_max_base * SENS_HIGH_FACTOR)

    base = estimate_damage(flood["flood_area_km2"], prob, duration["days"], month,
                            FLOOD_DEPTH_CM_ASSUMPTION)
    low = estimate_damage(flood["flood_area_km2"], prob, duration["days"], month,
                           FLOOD_DEPTH_CM_ASSUMPTION, sens_override=sens_low)
    high = estimate_damage(flood["flood_area_km2"], prob, duration["days"], month,
                            FLOOD_DEPTH_CM_ASSUMPTION, sens_override=sens_high)

    def scenario_for(damage_dict, salvage_frac):
        """Uniform early-harvest salvage: salvage_frac of the damaged area is
        saved, i.e. damaged_km2 *= (1 - salvage_frac). Scenario-only
        assumption, not a field-calibrated warning-to-salvage relationship
        (no such study is in this repo or was cited in this run) --
        UNSOURCED, marked as such."""
        damaged_km2 = damage_dict["damaged"] * (1 - salvage_frac)
        lost_tons = damaged_km2 * BORO_YIELD_KM2
        loss_bdt = lost_tons * BORO_PRICE_BDT
        return {
            "salvage_fraction": salvage_frac,
            "damaged_km2": round(damaged_km2, 1),
            "lost_tons": round(lost_tons, 0),
            "loss_bdt_crore": round(loss_bdt / 1e7, 2),
        }

    no_warning = {
        "loss_bdt_crore": base["bdt_crore"],
        "loss_bdt_crore_low": low["bdt_crore"],
        "loss_bdt_crore_high": high["bdt_crore"],
        "damaged_km2": base["damaged"],
        "lost_tons": base["lost_tons"],
        "farmers_exposed": base["farmers"],
    }
    salvage_scenarios = []
    for s in SALVAGE_FRACTIONS:
        base_s = scenario_for(base, s)
